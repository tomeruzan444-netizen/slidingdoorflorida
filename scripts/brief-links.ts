/** Writes the "as built" internal-link map into section 8 of each brief. Run: npx tsx scripts/brief-links.ts */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pages, pathFor } from "../content/pages";
import { contextualLinks, readMdx, ROOT } from "./lib/content";

const out = new Map<string, Set<string>>();
const inn = new Map<string, Set<string>>();
for (const p of pages) {
  const from = pathFor(p.slug);
  for (const l of contextualLinks(readMdx(p.slug))) {
    if (l === from) continue;
    (out.get(from) ?? out.set(from, new Set()).get(from)!).add(l);
    (inn.get(l) ?? inn.set(l, new Set()).get(l)!).add(from);
  }
}
for (const p of pages.filter((p) => p.kind !== "utility")) {
  const file = join(ROOT, "briefs", `${p.slug || "home"}.md`);
  if (!existsSync(file)) continue;
  const path = pathFor(p.slug);
  const section = `## 8. Internal links (as built, generated by scripts/brief-links.ts)\n\n- Links out to: ${[...(out.get(path) ?? [])].join(", ") || "none"}\n- Linked from: ${[...(inn.get(path) ?? [])].join(", ") || "none"}\n`;
  const text = readFileSync(file, "utf8");
  const i = text.search(/^## 8\./m);
  writeFileSync(file, (i >= 0 ? text.slice(0, i) : text + "\n") + section);
  console.log("updated", file);
}
